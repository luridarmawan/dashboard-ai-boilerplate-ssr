import type { ColumnDef, TableDef } from '../descriptor.ts';

/**
 * Emitters: descriptor → TypeScript source of a Drizzle schema, one function per dialect.
 *
 * Pure functions (string in, string out) so they can be tested without touching disk, and
 * so the §4.3 portability rules are visible in one place: the mapping below IS the PRD's
 * "type portability rules" table, expressed as code.
 */

export type Dialect = 'mysql' | 'pg' | 'sqlite';

const HEADER = (dialect: Dialect): string =>
  `// GENERATED by \`bun db:codegen\` from packages/db/schema/*.def.ts — DO NOT edit by hand.
// Dialect: ${dialect}. The descriptors are the source of truth; change them and regenerate.
/* biome-ignore-all lint: generated file */
`;

// ---------------------------------------------------------------------------
// MySQL / MariaDB
// ---------------------------------------------------------------------------

const MYSQL_IMPORTS = [
  'bigint',
  'boolean',
  'datetime',
  'decimal',
  'index',
  'int',
  'json',
  'mysqlTableCreator',
  'uniqueIndex',
] as const;
const MYSQL_CUSTOM = [
  'asciiVarchar',
  'utf8LongText',
  'utf8Text',
  'utf8Varchar',
  'uuidChar',
] as const;

function mysqlColumn(name: string, c: ColumnDef): string {
  const t = c.type;
  let e: string;
  switch (t.kind) {
    case 'uuid':
      e = `uuidChar('${name}')`;
      break;
    case 'varchar':
      e = t.identifier
        ? `asciiVarchar('${name}', { length: ${t.length} })`
        : `utf8Varchar('${name}', { length: ${t.length} })`;
      break;
    case 'enum': // native enums are forbidden — varchar + application constraint (§4.3)
      e = `utf8Varchar('${name}', { length: ${t.length} })`;
      break;
    case 'text':
      e = `utf8Text('${name}')`;
      break;
    case 'longtext':
      e = `utf8LongText('${name}')`;
      break;
    case 'int':
      e = `int('${name}')`;
      break;
    case 'bigint':
      e = `bigint('${name}', { mode: 'number' })`;
      break;
    case 'boolean':
      e = `boolean('${name}')`; // tinyint(1); Drizzle normalizes
      break;
    case 'datetime':
      e = `datetime('${name}', { fsp: 3 })`; // always UTC
      break;
    case 'json':
      e = `json('${name}')`;
      break;
    case 'decimal':
      e = `decimal('${name}', { precision: 18, scale: 4 })`;
      break;
  }
  return e + modifiers(c, { now: '.default(sql`CURRENT_TIMESTAMP(3)`)' });
}

export function emitMysql(tables: readonly TableDef[]): string {
  const sorted = sortTables(tables);
  const body = sorted.map((t) => emitTable(t, mysqlColumn)).join('\n\n');
  return `${HEADER('mysql')}
import { sql } from 'drizzle-orm';
import { ${MYSQL_IMPORTS.join(', ')} } from 'drizzle-orm/mysql-core';
import { ${MYSQL_CUSTOM.join(', ')} } from '../dialect/mysql-types.ts';

// O-2: optional table prefix so several apps can share one database.
const TABLE_PREFIX = process.env.TABLE_PREFIX ?? '';
const table = mysqlTableCreator((name) => \`\${TABLE_PREFIX}\${name}\`);

${body}

${emitFooter(sorted)}`;
}

